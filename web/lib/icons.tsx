/** All valid preset keys, in display order — drives the picker grid. */
export const PRESET_ICON_KEYS = Object.keys(PRESET_ICONS);

/** True iff `key` names a bundled preset icon. */
export function isPresetIcon(key: string): boolean {
  return key in PRESET_ICONS;
}

/**
 * Render one bundled preset icon by key. Returns `null` (renders nothing) for
 * an unknown key so a stale value can never throw — callers fall back to the
 * default glyph via {@link QuickLinkIcon}.
 */
export function PresetIcon({ name, size = 16 }: { name: string; size?: number }): ReactNode {
  const inner = PRESET_ICONS[name];
  if (!inner) return null;
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {inner}
    </svg>
  );
}

/**
 * Render a Quick Link's icon with the documented precedence:
 * `image` (PNG data URI → `<img>`) → `preset` (bundled SVG) → glyph (`icon`
 * text) → default `↗`. A broken/oversized image data URI falls back to the
 * default glyph via `<img onError>`, so a row never renders a broken image.
 */
export function QuickLinkIcon({ link, size = 16 }: { link: QuickLink; size?: number }): ReactNode {
  if (link.icon_kind === "image" && link.icon_value) {
    return (
      <>
        {/* eslint-disable-next-line @next/next/no-img-element -- data: URI, not a remote asset; next/image can't optimize it and would force a loader */}
        <img
          src={link.icon_value}
          alt=""
          className="shrink-0 object-contain"
          onError={(event) => {
            // Hide the broken <img> and reveal the sibling fallback glyph.
            event.currentTarget.style.display = "none";
            const fallback = event.currentTarget.nextElementSibling as HTMLElement | null;
            if (fallback) fallback.style.display = "inline";
          }}
          style={{ width: size, height: size }}
        />
        <span style={{ display: "none" }} aria-hidden="true">
          {link.icon || "↗"}
        </span>
      </>
    );
  }
  if (link.icon_kind === "preset" && link.icon_value && isPresetIcon(link.icon_value)) {
    return <PresetIcon name={link.icon_value} size={size} />;
  }
  return <>{link.icon || "↗"}</>;
}
